// Generates public/practice.js from tools/practice-spec.js.
// Usage: node tools/build-practice.js            (build)
//        node tools/build-practice.js --validate (also cross-check against the lesson programs)
const fs = require("fs"), path = require("path"), vm = require("vm"), os = require("os");
const { spawnSync } = require("child_process");
const spec = require("./practice-spec.js");

const out = {};
for (const [id, p] of Object.entries(spec)) {
  out[id] = { task: p.task, inp: p.inp, out: p.out, tests: p.tests.map((t) => ({ input: t, expected: p.f(t) })) };
}
const body = "// AUTO-GENERATED by tools/build-practice.js. Do not edit by hand.\nwindow.PRACTICE = " + JSON.stringify(out, null, 1) + ";\n";
fs.writeFileSync(path.join(__dirname, "..", "public", "practice.js"), body);
console.log("practice.js written for", Object.keys(out).length, "questions,", Object.values(out).reduce((a, p) => a + p.tests.length, 0), "tests");

if (process.argv.includes("--validate")) {
  const w = {};
  for (let i = 1; i <= 5; i++) vm.runInNewContext(fs.readFileSync(path.join(__dirname, "..", "public", `questions${i}.js`), "utf8"), { window: w });
  const tok = (s) => (s.toLowerCase().match(/-?\d+|[a-z]+/g) || []);
  let bad = 0;
  for (const q of w.QUESTIONS) {
    const lv = q.levels.find((l) => l.i !== undefined && !(q.id === 42 || q.id === 43));
    if (!lv || [1, 4, 39, 37, 44].includes(q.id)) continue;       // formats differ on purpose
    const d = fs.mkdtempSync(path.join(os.tmpdir(), "v-"));
    fs.writeFileSync(d + "/Main.java", lv.c);
    spawnSync("javac", ["Main.java"], { cwd: d });
    for (const t of out[q.id].tests) {
      const r = spawnSync("java", ["-cp", d, "Main"], { input: t.input + "\n", encoding: "utf8", timeout: 8000 });
      const got = tok(r.stdout), exp = tok(t.expected);
      const missing = exp.filter((x) => !got.includes(x));
      if (missing.length) { bad++; console.log(`Q${q.id} input=${JSON.stringify(t.input)}\n   expected=${JSON.stringify(t.expected)}\n   lesson  =${JSON.stringify(r.stdout.trim().slice(0, 120))}`); }
    }
    fs.rmSync(d, { recursive: true, force: true });
  }
  console.log("validation mismatches:", bad);
}
